#!/usr/bin/env python3
"""Fallback cjc-wrapper: build native libraries and drive cjc + cbc-compiler.

Recognised on the cjc command line:
  -o <out>              output name
  <NAME>.o              C object: build lib<NAME>.so from it
  -l <NAME> / -l<NAME>  link against lib<NAME>.so
  -L <PATH> / -L<PATH>  library search path
"""

import glob
import os
import shlex
import subprocess
import sys


def run(cmd):
    """Run cmd; on failure exit with its status (like bash `set -e`)."""
    status = subprocess.call(cmd)
    if status:
        sys.exit(128 - status if status < 0 else status)


def is_elf_object(path):
    """True if path is an ELF relocatable object (e.g. `clang -c` output)."""
    try:
        out = subprocess.run(["readelf", "-h", path], stdout=subprocess.PIPE,
                             stderr=subprocess.DEVNULL,
                             universal_newlines=True).stdout
    except OSError:
        return False
    return "REL (Relocatable" in out


def parse_args(args):
    """Split the cjc command line into (out, native_names, lib_paths)."""
    out = ""
    native_names = []
    lib_paths = []
    i = 0
    while i < len(args):
        arg = args[i]
        nxt = args[i + 1] if i + 1 < len(args) else None

        if arg == "-o" and nxt is not None:
            out = nxt
            i += 2
        elif arg == "-L" and nxt is not None:
            lib_paths.append(nxt)  # library path for launcher
            i += 2
        elif arg.startswith("-L") and len(arg) > 2:
            lib_paths.append(arg[2:])
            i += 1
        elif arg == "-l" and nxt is not None:
            native_names.append(nxt)  # shared lib for -foreignlibs
            i += 2
        elif arg.startswith("-l") and len(arg) > 2:
            native_names.append(arg[2:])
            i += 1
        elif arg.endswith(".o"):
            # Static object: instead build a shared lib and register it.
            name = arg[:-2]
            run(["cc", "-shared", "-Wl,-Bsymbolic", "-o", f"lib{name}.so", arg])
            native_names.append(name)
            i += 1
        else:
            i += 1
    return out, native_names, lib_paths


def repair_fake_libs(names, lib_dirs):
    """Relink lib<name>.so files that are plain ELF objects (built with
    `clang -c`) into real shared libraries the runtime can dlopen."""
    for name in names:
        for d in lib_dirs:
            lib = os.path.join(d, f"lib{name}.so")
            if os.path.isfile(lib) and is_elf_object(lib):
                run(["cc", "-shared", "-Wl,-Bsymbolic", "-o", lib + ".tmp", lib])
                os.replace(lib + ".tmp", lib)


def write_foreignlibspath(lib_paths):
    """Let launcher-wrapper prepend the -L paths to LD_LIBRARY_PATH."""
    with open(".foreignlibspath", "w") as f:
        f.write("# generated by cjc-wrapper\n")
        if lib_paths:
            quoted = ":".join(shlex.quote(p) for p in lib_paths)
            f.write("export LD_LIBRARY_PATH=" + quoted + "${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}\n")
        else:
            f.write("# no -L paths\n")


def genlibrary(out, names, lib_dirs, script_dir):
    """Produce <out>.cbc, registering foreign libs for the engine."""
    # Cangjie packages have lib<name>.so.cbc and run as bytecode: skip them.
    foreign = [n for n in names
               if not any(os.path.isfile(os.path.join(d, f"lib{n}.so.cbc")) for d in lib_dirs)]
    cmd = ["java", "-jar", os.path.join(script_dir, os.pardir, "tools", "bin", "cbc-compiler.jar"),
           *sorted(glob.glob("*.chir")), "+genlibrary", f"-outputname={out}"]
    if foreign:
        cmd.append("-foreignlibs=" + ",".join(foreign))
    run(cmd)


def main():
    script_dir = os.path.dirname(sys.argv[0]) or "."
    out, native_names, lib_paths = parse_args(sys.argv[1:])
    lib_dirs = ["."] + lib_paths

    repair_fake_libs(native_names, lib_dirs)
    write_foreignlibspath(lib_paths)

    run(["cjc", "--emit-chir"] + sys.argv[2:])  # like bash: cjc --emit-chir "${@:2}"

    if out and not out.endswith(".a") and glob.glob("*.chir"):
        genlibrary(out, native_names, lib_dirs, script_dir)


if __name__ == "__main__":
    main()
