class BitStreamSuite extends AnyFunSuite with Matchers {

  private def asByteArray(bytes: Int*) = {
    val realBytes = new Array[Byte](bytes.length)
    for (i <- realBytes.indices) {
      val x = bytes(i)
      assert(0 <= x && x <= 0xFF)
      realBytes(i) = x.toByte
    }
    realBytes
  }

  private def bytes(bytes: Int*) = Bitstream.raw(asByteArray(bytes *))

  private def checkNothingLeft(bs: Bitstream): Unit = {
    try {
      bs.readBit()
      fail("there should be nothing left to read!")
    } catch {
      case _: Errors.Error =>
        // passed
    }
  }

  private def interceptError(action: => Any): Unit = {
    try {
      val result = action
      val message = result match {
        case () => "error was expected"
        case _ => s"error was expected, but got $result"
      }
      fail(message)
    } catch {
      case _: Errors.Error =>
        // passed
    }
  }

  private def b(s: String): Int = {
    val prepared = s.replace("_", "")
    Integer.parseInt(prepared, 2)
  }

  test("Bit") {
    val bs = bytes(b("1111_0101"), b("0101_1001"))

    assertResult(1)(bs.readBit())
    assertResult(0)(bs.readBit())
    assertResult(1)(bs.readBit())
    assertResult(0)(bs.readBit())

    assertResult(1)(bs.readBit())
    assertResult(1)(bs.readBit())
    assertResult(1)(bs.readBit())
    assertResult(1)(bs.readBit())

    // next byte, please
    assertResult(1)(bs.readBit())
    assertResult(0)(bs.readBit())
    assertResult(0)(bs.readBit())
    assertResult(1)(bs.readBit())

    assertResult(1)(bs.readBit())
    assertResult(0)(bs.readBit())
    assertResult(1)(bs.readBit())
    assertResult(0)(bs.readBit())

    checkNothingLeft(bs)
  }

  test("BitOutOfRange") {
    val bs = bytes(0, 0)
    for (_ <- 0 until 16) {
      bs.readBit()
    }
    interceptError {
      bs.readBit()
