  }

  test("Bits") {
    val bs = bytes(b("1111_0101"), b("0101_1001"))

    assertResult(b("0101"))(bs.readBits(4))
    assertResult(b("1001_1111"))(bs.readBits(8))
    assertResult(b("1"))(bs.readBits(1))
