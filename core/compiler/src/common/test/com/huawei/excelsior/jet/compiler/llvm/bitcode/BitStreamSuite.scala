  private val DEBUG = false

  private def parseWhole(bytes: Array[Byte], splitByBlocks: Boolean) = {

    val MAGIC = -1
    val ENTER_BLOCK = -2
    val END_BLOCK = -3
    val END_OF_STREAM = -4

    val result = new ArrayBuffer[Long]

    Bitstream.parseWhole(DataInput.from(bytes), new BitstreamConsumer() {
      var ctx: Bitstream.Context = _
      var splitLevel = -1
      var splitDepth = 0

      def put(data: Long*): Unit = {
        result ++= data
      }

      def log(msg: String): Unit = {
        if (DEBUG) {
          println(s"${" " * ctx.depth}$msg")
        }
      }

      override def setContext(ctx: Bitstream.Context): Unit = {
        this.ctx = ctx
      }

      override def magic(magicValue: Int) = {
        put(MAGIC, magicValue)
        log(s"magic: ${Integer.toHexString(magicValue)}")
        true
      }

      override def enterBlock(id: Int) = {
        val split = splitByBlocks && splitLevel != ctx.depth
        if (split) {
          val prevCtx = ctx
          val blockCtx = ctx.makeSingleBlockContext()
          val prevSplitLevel = splitLevel
          splitLevel = ctx.depth
          splitDepth += 1
          log(s"split at B#$id; depth $splitDepth")
          try {
            Bitstream.parseSingleBlock(DataInput.from(bytes), blockCtx, this)
          } catch {
            case e: Throwable =>
              fail(s"unexpected error: $e")
          }
          ctx = prevCtx
          splitLevel = prevSplitLevel
          splitDepth -= 1
          false // skip
        } else {
          put(ENTER_BLOCK, id)
          log(s"B#$id {")
          true
        }
      }

      override def endBlock(id: Int): Unit = {
        put(END_BLOCK)
        log("}")
      }

      override def record(code: Int, opsCount: Int, hasBlob: Boolean): Unit = {
        put(code, opsCount)
        val ops = new java.lang.StringBuilder
        for (i <- 0 until opsCount) {
          put(ctx.operand(i))
          if (i != 0) ops.append(", ")
          ops.append(java.lang.Long.toUnsignedString(ctx.operand(i)))
        }
        if (hasBlob) {
          val blob = ctx.getBlob
          put(blob.length)
          ops.append(s", blob[${blob.length} bytes] = ")
          ops.append(s"\"${new String(blob)}\"")
        }
        log(s"R#$code [$ops]")
      }

      override def endOfStream(): Unit = {
        if (splitDepth == 0) {
          put(END_OF_STREAM)
          log("EOS")
        } else {
          log(s"END split; depth $splitDepth")
        }
      }

      override def blockInfoAllowed = {
        log("(blockinfo)")
        ctx.blockId == Bitcode.BlockIds.MODULE_BLOCK
      }
    })

    result.toArray
  }

