      override def newMultiObjectArray(index: Int, dimNum: Int): Unit = {
        import ConstantPoolAccessResult.*

        assert(managedContext)
        assert(dimNum > 0)

        val arrayTypeAccess = cp.getType(index)
        arrayTypeAccess.getResult match {
          case OK | DEFERRED =>
            val arrayType = arrayTypeAccess.getObject
            assert(arrayType.isJBCArray)
            val allDimNum = arrayType.getArrayDimnum
            assert(allDimNum >= dimNum)

            val dims = Seq.fill(dimNum)(st.pop()).reverse
            val array = if (arrayType.isDeferred) {
              tryDeferred(arrayType.getName) {
                Deferred.NewArray(index, allDimNum, dims.length)(dims: _*)
              }
            } else {
              ensurePrepared(PreparationRequired.forType(arrayType))
              NewArray(SignatureType.fromSymType(arrayType))(dims: _*)
            }
            st push array

          case ERROR =>
            throwErrorAndHalt(arrayTypeAccess.getError)
        }
      }

      // bytecode.parsing.ControlFlowParser intentionally places each monitor operation in the end of block so this method may not fail
      private def findMonitorEnter(block: BBlock) = ScalaCollections.firstElement(block.spineBackward) match {
        case Some(enter: MonitorEnter) => enter
        case _ => shouldNotReachHere(s"$block should contain MonitorEnter")
      }

      def monitorEnter(): Unit = {
        assert(managedContext)

        val outerRegion = cfState.outerMonitorBlockMap.get(block) map { outerEnterBlock =>
          val outerEnter = findMonitorEnter(outerEnterBlock)
          assert(outerEnter dominates block) // structured locking analyzer should provide this
          outerEnter.syncRegion
        }

        val obj = st.pop()
        val lockObj = getLockableObj(obj)
        nullCheck(lockObj)
        MonitorEnter(lockObj, SynchronizedRegion(outerRegion))
      }

      def monitorExit(): Unit = {
        assert(managedContext)

        val (syncRegion, requiresNC) =
          if (isUnstructuredLocking) {
            (MonitorExit.IntentionallyInvalidPairedEnter(), true)
          } else cfState.pairedEnterBlockMap.get(block) match {
            case Some(pairedEnterBlock) =>
              val enter = findMonitorEnter(pairedEnterBlock)
              assert(enter dominates block)
              // in case of structured locking it is guaranteed that obj is already null-checked
              (enter.syncRegion, false)

            case None =>
              shouldNotReachHere("locking is considered structured but we have no paired enter")
          }

        val obj = st.pop()
        val lockObj = getLockableObj(obj)
        nullCheck(lockObj, forceTrusted = !requiresNC)
        MonitorExit(lockObj, syncRegion)
      }

      private def getLockableObj(obj: Node): Node = nodeType(obj) match {
        // implicit synchronization on scala/runtime/LazyRef and other wrappers is may be inserted by scalac
        // in implementation of lazy val local variables, so we need to switch synchronization target to special injected lock field
        case tpe: UpperBounded if tpe.root.symType.isXScalaType => tpe.root.symType match {
          case Scala.Runtime.Support.LazyType(lazyType) =>
            val lazyField = lazyType._lock
            val lockField = XScala.Sync.LockJET.lock

            val lazyLock    = GetField(lazyField)(obj)
            val lockableObj = GetField(lockField)(lazyLock)
            lockableObj
        }
        case _  =>
          if (rootDeclaringClass.isXScalaType) {
            assert(rootMethod.getName == "sync" && rootDeclaringClass.getName == "xscala/sync/LockJET",
              "synchronization in Scala LP should be used only for Lock objects")
          }
          obj
      }

      def tryDeferred(errmsg: => String)(node: => Deferred): Deferred = {
        if (env.enabled(LogUnresolvedErrors)) {
          println(s"UNRESOLVED: deferred $errmsg at ${currentPosition()}")
        }

        if (languagePack.supports(JAVA) && env.enabled(IgnoreResolveErrors)) {
          node
        } else {
          RTSCall(RTSProc.JR_FatalError)(AJString.bstr(s"Unsupported deferred: $errmsg at ${currentPosition()}"))
          haltBlock(Halt.afterRTSCall(RTSProc.JR_FatalError, s"Unsupported deferred: $errmsg at ${currentPosition()}"))
        }
      }
    }
  }
