/**
 * Java bytecode data flow analysis and operations builder.
 * Used as second pass for java bytecode parsing.
 *
 * During first ([[com.huawei.excelsior.jet.compiler.opt.frontend.bytecode.ControlFlow ControlFlow]] pass we split bytecode
 * range by basic blocks and formed ControlFlow graph of basic blocks.
 * Here we provide abstract interpretation for each basic block completing
 * [[com.huawei.excelsior.jet.compiler.opt.ir.AbstractInterpreterComponent.AbstractInterpreter AbstractInterpreter]]
 * interface with `interpret` method.
 *
 * During abstract interpretation of a block, IR nodes are generated by corresponding bytecode instructions.
 *
 * @author paul
 */
trait DataFlow extends VMStates
                  with Intrinsics
                  with ConstBranchElimination
                  with ClinitAnalysisConfig
                  with Toolbox
                  with Arrays { self: Universe with ControlFlow =>

  case class ParseInfo(needMemBarBeforeReturn: Boolean)

  def parseMethod(method: Method, cfState: ControlFlowParsingState, args: Seq[Node]): ParseInfo = env.withDebugPosition(curPos()) {
    new BytecodeParser(method, cfState, args).parse()
  }

  private class BytecodeParser(method: Method, cfState: ControlFlowParsingState, args: Seq[Node]) {
    locally {
      val ic = Position.inlineContext(curPos()) getOrElse shouldNotReachHere("should be covered by withPos()")
      assert(method == ic.method)
    }

    private var bc: Int = -1
    def currentPosition() =
      if (bc >= 0) currentMethodPos(bc) else NoPosition

    val attr = method.codeAttribute
    val cp = method.getDeclaringClass.getClassConstantPool
    val bcIterator = new BytecodeIterator(attr)
    private var needMemBarBeforeReturn: Boolean = false

    val blockParsing = new Breaks

    private val managedContext = method.isManaged

    private val noNullCheck       = method.noNullCheck(env)
    private val noArrayIndexCheck = method.noArrayIndexCheck(env)
    private val noArrayStoreCheck = method.noArrayStoreCheck(env)

    if (method.isNonThrowing) {
      // At the moment, CompilerInterfaceGenerator do not add @CompilerHint.StackCheckByCaller annotations,
      // so the `isExternal` is a workaround for methods from CompilerInterface.
      assert(method.shouldStackCheckByCaller || method.isExternal,
        s"Method ${method.getFullName} annotated with @NonThrowing, so it must be annotated with @CompilerHint.StackCheckByCaller.")
    }

    class VMStateInterpreter extends AbstractInterpreter {
      type State = VMState

      override protected def debug(msg: String): Unit = {
        if (env.enabled(DetailedParsingLogs)) {
          dbgPrinter.debugNodes("All graph after " + msg)
        }
      }

      private def registerXCtrl(n: Node, state: State, handler: XBlock): Unit = {
        if (handler != null) n match {
          case sn: SpinalNode if sn.canThrow =>
            val xpoint = sn.xpoint
            handler.addArg(xpoint)

            val xstate = state.fork().dropStack()
            xstate.xobj = Invalid
            xstate.memory = Invalid
            xstate.rewind(sn)
            xstate.add(xpoint)
            addXCtrl(xpoint, xstate)

          case _ =>
        }
      }

      protected def startInputState(b: Block) =
        new VMState(entryMemory, attr.maxLocals, attr.maxStack)

      protected def interpret(block: Block, state: VMState): Block = {
        require(state != null)
        val anchor = block.outCtrl match {
          case anchor: HandlerAnchor => anchor
          case x => assert(x == block.blockEnd); null
        }

        currentScope.inState(state) {
          withIdempotentDominance {
            // In IR built from bytecode there may be only one exception handler for a block.
            val xhandler = if (anchor != null) anchor.xHandler else null
            onCommit.withCallback(n => registerXCtrl(n, state, xhandler)) {
              state.add(block)
              if (anchor != null) {
                state.add(anchor)
              }
              block.blockEnd.inCtrl = null
              block.spineBackwardIsBroken = true

              // Here both memory and control dependencies become broken in this block.
              // Note that overall CFG remains valid, because block and its block end are still linked.
              // TODO: do not break IR and rework state so that it can keep this block together,
              //       while allowing insertion of new nodes in parsing and in insert code.

              val blockParser = new BlockParser(block, state)
              for (kind <- cfState.kinds.get(block)) {
                blockParsing.breakable {
                  kind match {
                    case PrologBlock                   => blockParser.parseProlog()
                    case exBlock: ExceptionStuffBlock  => blockParser.parseExStuff(exBlock)
                    case BytecodeRange(startPC, endPC) => bcIterator.iterate(blockParser, startPC, endPC)
                  }
                }
              }
              blockParser.adjustBlockEnd()
              block.spineBackwardIsBroken = false
              checkConsistency(CheckLevels.Desirable)(Block.verifyBlockControlNums(block))
              if (state.contextTypes != null) {
                ContextTypesMap.setMapAt(block.blockEnd, state.contextTypes)
              }
            }
          }
        }
        bc = -1
        if (anchor != null) {
          strikeOut(anchor)
        }
        block
      }

      override protected def interpretEdge(blockExit: BlockExit, state: VMState): ControlNode = {
        if (state.contextTypes != null) {
          val filter = state.contextTypes.makeFilter(blockExit)
          if (filter != null) {
            val branchExit = blockExit.asInstanceOf[Branch.Exit] // Otherwise it cannot be filter exit
            if (filter.isRedundant) {
              ContextTypesStats.updateOnRedundantFilterRemove(filter)
              return replaceByGoto(branchExit)
            } else {
              state.contextTypes.appendFilter(filter)
              ContextTypesMap.setMapAt(branchExit, state.contextTypes)
            }
          }
        }
        blockExit
      }
    }

    def parse(): ParseInfo = {
      val intp = new VMStateInterpreter
      withPosFactory(currentPosition) {
        Node.withImplicitArgConversion(enrichArg()) {
          intp.iterate()
        }
      }
      ParseInfo(needMemBarBeforeReturn)
    }

    private class BlockParser(block: Block, st: VMState) extends BytecodeProcessor {

      private def throwErrorAndHalt(error: ConstantPool.ErrorAccessInfo): Nothing = {
        var proc = error.getThrowProc
        var msg = error.getErrorMessage

        if (!managedContext) {
          msg = XString.ascii(s"${proc.toString}: $msg")
          proc = RTSProc.JR_FatalError
        }

        throwErrorAndHalt(proc, msg)
      }

      private def throwErrorAndHalt(proc: RTSProc, msg: XString): Nothing = {
        ErrorRTSCall(proc)(AJString.bstr(msg))
        haltBlock(Halt.afterRTSCall(proc, msg.toString))
      }

      private def throwErrorAndHalt(proc: RTSProc, args: Node*): Nothing = {
        ErrorRTSCall(proc)(args: _*)
        haltBlock(Halt.explained("java bytecode data-flow analysis"))
      }

      private enum BlockEndStatus {
        case RAW, ADJUSTED, IN_STATE
      }
      import BlockEndStatus.*

      private var blockEndStatus = RAW

      /** Ties `block`'s end to current control and current memory. Block ends are created in
        * ControlFlow (to form normal CFG) and we do not append them again in DataFlow, so they
        * will not appear in scope state, except when we replace block end by some other block end
        * during DataFlow processing.
        */
      def adjustBlockEnd(): Unit = {
        val end = block.blockEnd
        val inState = end == currentCtrl
        blockEndStatus match {
          case IN_STATE =>
            assert(inState)
          case ADJUSTED =>
            assert(!inState)
            assert(end.inCtrl == currentCtrl && end.inMemory == currentMemory)
          case RAW if inState =>
            blockEndStatus = IN_STATE
          case RAW =>
            assert(currentCtrl != null && currentMemory != null && currentCtrl.block == block)
            end.inCtrl = currentCtrl.asInstanceOf[UpperPoint]
            end.inMemory = currentMemory
            blockEndStatus = ADJUSTED
        }
      }

      //////////// ENTRY BLOCK ///////////////

      // if i'th local is not an arg, argIndex must be negative like -1
      def debugVarNode(i: Int, method: Method, lvt: Method.LocalVariablesTable, argIndex: Int = -1): StackAlloc = {
        val name = lvt.localName(i)
        val symType = typeProvider.parseSingleElementSignature(lvt.localSignature(i))
        val isPointer = symType.isTraceableReference

        val varType = JavaDwarfTypes.typeToDebugType(symType)

        val decl = None // Decl is optional, when required - extract decl info from LVT.
        val info = DebugLocalVar(name, varType, argIndex, isPointer, decl)

        StackAlloc.DebugVar(symType, info)
      }

      def parseProlog(): Unit = {
        bc = 0 // prolog code is treated as bytecode with position 0

        var localIdx = 0
        val lvt = method.codeAttribute.getLocalVariablesTable()
        for ((arg, i) <- args.zipWithIndex) {
          if (genDebug && lvt.nonEmpty) {
            // StackAlloc.DebugVar nodes should be used for args locals
            val dbgNode = debugVarNode(i, method, lvt.get, i)
            st(localIdx) = dbgNode
          }
          st(localIdx) = arg
          localIdx += method.getParamType(i).jbcKind.nslots
        }
        if (genDebug) {
          if (lvt.nonEmpty) {
            // StackAlloc.DebugVar nodes should be used for other locals
            val localsCount = lvt.map(_.localCount()).get
            var i = args.length
            while (i < localsCount) {
              val dbgNode = debugVarNode(i, method, lvt.get)
              val sigType = dbgNode match {
                case StackAlloc.DebugVar(t, _) => t
              }
              st(localIdx) = dbgNode
              localIdx += sigType.jbcKind.nslots
              i += 1
            }
          }
          DebugPrologueEndBreakpoint()
        }

        val methodHostClass = method.getDeclaringClass

        if (env.enabled(PreparationAsserts) && managedContext && methodHostClass.preparationRequired) {
          PreparationCheck(methodHostClass, PreparationKind.PROLOGUE_ASSERTION)()
        }

        if (method.isStatic && methodHostClass.hasRunTimeTypeInfo) {
          if (managedContext) {
            if (!method.isPreClinited) {
              Clinit(methodHostClass)()
            } else if (Env.isWorkMode && !methodHostClass.isPreClinited) {
              // Verify clinit optimizations in static non-clinit methods.
              // We could not create "trusted" clinit check because it will be removed by context types.
              ClinitedAssert(methodHostClass)()
            }

          } else if (Env.isWorkMode && !methodHostClass.isPreClinited) {
            InitializedAssert(methodHostClass)()
          }
        }

        if (env.isTurboClinitHost(method)) {
          for (c <- typeProvider.getTurboClinitedClasses) {
            assert(!c.isPreClinited && !c.isTurboClinitedIn(method))
            Clinit(c)()
          }
        }
      }

      //////////// BYTECODE EXCEPTION TABLES ///////////////

      def parseExStuff(kind: ExceptionStuffBlock): Unit = {
        bc = Position.offset(block.pos) getOrElse -1
        kind match {
          case XBlockKind(None) =>
            st.xobj = block.asInstanceOf[XBlock].catchNode
          case XBlockKind(Some(domain)) =>
            st.xobj = ConvertDomain(domain)(block.asInstanceOf[XBlock].catchNode)

          case ThrowBlock =>
            withPos(currentMethodSyntheticPos) { makeThrow(st.xobj) }
            st.xobj = Invalid

          case TransitionToHandler =>
            st push st.xobj
            st.xobj = Invalid

          case ExceptionCheck(catchType) =>
            // TODO-SYMLEVEL think about cast
            val iof = instanceOf(catchType, st.xobj)
            makeIf(Cmp(iof.tpe, Condition.NE)(iof, IConst(0)))
        }
      }

      //////////// COMMON ///////////////

      private var lastPosition: BytecodePosition = _

      override def startInstruction(offset: Int, nextOffset: Int): Unit = {
        bc = offset
        if (method.isStrictMemory) {
          MemBarrier(Set(STRICT_MEM))()
        }
        if (genDebug) {
          val lineNumber = method.codeAttribute.findLineNumber(offset)
          val position = BytecodePosition(BytecodeOffset.SYNTHETIC, lineNumber, ColumnNumber.UNKNOWN, currentInlineContext)
          if (lastPosition == null || lastPosition != position) {
            withPos(position) { DebugTextPosBreakpoint() }
            lastPosition = position
          }
        }
      }

      def haltBlock(haltProto: Halt.Proto): Nothing = {
        removeBlockEnd(block.blockEnd)
        haltProto()
        blockParsing.break()
      }

      def makeReturn(retValue: Node): Unit = {
        val ret = block.blockEnd.asInstanceOf[Return]
        val proxy = ret.inValue
        assert(proxy.isInstanceOf[Proxy] && proxy.singleUse == ret)
        proxy.replaceBy(retValue)
      }

      def makeThrow(xobj: Node): Unit = {
        Throw(xobj)
      }

      def makeBranch(branch: Branch, selector: Node): Unit = {
        val proxy = branch.selector
        assert(proxy.isInstanceOf[Proxy] && proxy.singleUse == branch)
        proxy.replaceBy(selector)
        adjustBlockEnd()
        tryEliminateConstBranch(branch)
      }

      def makeIf(condition: Node): Unit = {
        makeBranch(block.blockEnd.asInstanceOf[If], condition)
      }

      def makeSwitch(selector: Node): Unit = {
        makeBranch(block.blockEnd.asInstanceOf[Switch], selector)
      }

      def nullCheck(obj: Node, forceTrusted: Boolean = false): Unit = {
        if (obj.tpe == ThinType) {
          assert(!forceTrusted)
          ThinNullCheck(trusted = noNullCheck)(obj)
        } else {
          NullCheck(trusted = forceTrusted || noNullCheck || !managedContext)(obj)
        }
      }

      def clinitCheck(klass: symlevel.ClassType): Unit = {
        if (managedContext) {
          Clinit(klass)()
        } else if (Env.isWorkMode && !klass.isPreClinited) {
          InitializedAssert(klass)()
        }
      }

      def pushCPEntry(index: Int): Unit = {
        import bytecode.Tag.*
        import com.huawei.excelsior.jet.compiler.bytecode.ConstantPoolAccessResult.*

        val node = (cp.getTag(index): @unchecked) match {
          case INTEGER => IConst(cp.getInt(index))
          case LONG =>    LConst(cp.getLong(index))

          case FLOAT =>   FConst(cp.getFloat(index))
          case DOUBLE =>  DConst(cp.getDouble(index))

          case STRING =>
            val constStr = cp.getConstString(index)

            if (managedContext) {
              ensurePrepared(PreparationRequired.forConstString(constStr))
            } else {
              // Nothing to do. ConstString are allowed in unmanaged context only for AJ intrinsics implementation.
              // If any one will survive through compiler, assert in lowering will fail.
            }

            // The host check is possible because AJ, Java and Scala classes contain only their own string literals.
            val strType = if (constStr.getHost.isJavaReference) {
              typeProvider.getStringType
            } else if (constStr.getHost.isXScalaType) {
              typeProvider.getXScalaString
            } else {
              typeProvider.getAJStringType
            }
            // It is controlled as a workaround for JET-10876.
            // Bind it to entry of current method where current class must be already prepared.
            ConstString(constStr, strType).withExplicitArgs(entryBlock)

          case CLASS =>
            val access = cp.getType(index)
            access.getResult match {
              case OK =>
                if (managedContext) {
                  ClassObject(access.getObject)()
                } else {
                  Null()   // argument of intrinsic, ignore it
                }

              case DEFERRED =>
                tryDeferred(access.getObject.getName) {
                  Deferred.ClassObject(index)()
                }

              case ERROR =>
                throwErrorAndHalt(access.getError)
            }

          case METHOD_TYPE => Deferred.MethodType(index)()

          case METHOD_HANDLE => Deferred.MethodHandle(index)()
        }

        st push node
      }

      def pushConst(tkind: BytecodeTypeKind, value: Int): Unit = {
        val node = (tkind: @unchecked) match {
          case BytecodeTypeKind.DOUBLE => DConst(value.toDouble)
          case BytecodeTypeKind.FLOAT  => FConst(value.toFloat)
          case BytecodeTypeKind.LONG   => LConst(value.toLong)
          case BytecodeTypeKind.INT | BytecodeTypeKind.BYTE | BytecodeTypeKind.SHORT => IConst(value)
          case BytecodeTypeKind.CLASS  => assert(value == 0); Null()
        }
        st push node
      }

      private def checkLocal(tkind: BytecodeTypeKind, node: Node): Unit = {
        if (tkind.isReference) {
          assert(node.tpe.isTraceableRefType || node.tpe == ThinType || node.tpe == ReturnAddressType)
        } else {
          // Note: do not forget about "bottom" type. TODO: should we explicitly check that node.isInstanceOf[NoValue] here?
          assert(Type.lteq(node.tpe, ValueType(fromBytecode(tkind))))
        }
      }

      def pushLocal(tkind: BytecodeTypeKind, index: Int): Unit = {
        val node = st(index)
        checkLocal(tkind, node)
        st push node
      }

      def storeLocal(tkind: BytecodeTypeKind, index: Int): Unit = {
        val node = st.pop()
        checkLocal(tkind, node)
        st(index) = node
      }

      def arithOp(tkind: BytecodeTypeKind, op: ArithOp): Unit = {
        import ArithOp.*

        val tpe = ValueType(fromBytecode(tkind))
        val node = if (op == NEG) {
          val a = st.pop()
          Neg(tpe)(a)

        } else {
          val a2 = st.pop()
          val a1 = st.pop()
          (op: @unchecked) match {
            case ADD  => Add(a1, a2)
            case SUB  => Sub(a1, a2)

            case MUL  => Mul(a1, a2)

            case DIV | REM =>
              if (tpe.isIntegralType) {
                DivisorCheck(trusted = !managedContext)(a2)
                op match {
                  case DIV => IDiv(tpe)(a1, a2)
                  case REM => IRem(tpe)(a1, a2)
                  case _ => shouldNotReachHere(op)
                }
              } else {
                assert(tpe.isFloatingPointType)
                op match {
                  case DIV => FDiv(tpe)(a1, a2)
                  case REM => FRem(tpe)(a1, a2)
                  case _ => shouldNotReachHere(op)
                }
              }

            case AND  => And(a1, a2)
            case OR   => Or(a1, a2)
            case XOR  => Xor(a1, a2)


            case CMP | CMPL | CMPG => ThreeCmp(tpe, op)(a1, a2)
            case LSL | ASR | LSR => Shift(op, a1, a2)
          }
        }
        st push node
      }

      def convert(op: ConvertOp): Unit = {
        val from = op.srcKind
        val to   = op.dstKind

        val arg  = st.pop()
        val value = JavaConvert(from, to)(arg)
        st push value
      }

      def stackOp(op: Bytecode): Unit = {
        val depth = st.stackDepth
        def dropped(n: Int) = (st.stackDepth == depth - n)
        def shouldDrop(n: Int): Unit = { assert(dropped(n)) }
        def pop2() = (st.pop(), st.pop())

        (op: @unchecked) match {
          case POP =>
            st.pop()
            shouldDrop(1)

          case POP2 =>
            st.pop()
            if (dropped(1)) {
              st.pop()
            }
            shouldDrop(2)

          case SWAP =>
            val (v1, v2) = pop2()
            shouldDrop(2)
            st.push(v1, v2)

          case DUP =>
            val x = st.pop()
            shouldDrop(1)
            st.push(x, x)

          case DUP_X1 =>
            val (v1, v2) = pop2()
            shouldDrop(2)
            st.push(v1, v2, v1)

          case DUP_X2 =>
            val v1 = st.pop()
            shouldDrop(1)
            val v2 = st.pop()
            if (dropped(2)) {
              val v3 = st.pop()
              shouldDrop(3)
              st.push(v1, v3, v2, v1)
            } else {
              shouldDrop(3)
              st.push(v1, v2, v1)
            }

          case DUP2 =>
            val v1 = st.pop()
            if (dropped(1)) {
              val v2 = st.pop()
              shouldDrop(2)
              st.push(v2, v1, v2, v1)
            } else {
              shouldDrop(2)
              st.push(v1, v1)
            }

          case DUP2_X1 =>
            val v1 = st.pop()
            if (dropped(1)) {
              val (v2, v3) = pop2()
              shouldDrop(3)
              st.push(v2, v1, v3, v2, v1)
            } else {
              val v2 = st.pop()
              shouldDrop(3)
              st.push(v1, v2, v1)
            }

          case DUP2_X2 =>
            val v1 = st.pop()
            if (dropped(1)) {
              val v2 = st.pop()
              shouldDrop(2)
              val v3 = st.pop()
              if (dropped(3)) {
                val v4 = st.pop()
                shouldDrop(4)
                st.push(v2, v1, v4, v3, v2, v1)
              } else {
                shouldDrop(4)
                st.push(v2, v1, v3, v2, v1)
              }
            } else {
              shouldDrop(2)
              val v2 = st.pop()
              if (dropped(3)) {
                val v3 = st.pop()
                shouldDrop(4)
                st.push(v1, v3, v2, v1)
              } else {
                shouldDrop(4)
                st.push(v1, v2, v1)
              }
            }

        }
      }

      def increment(local: Int, delta: Int): Unit = {
        st(local) = Add(st(local), IConst(delta))
      }

      override def unaryIf(tkind: BytecodeTypeKind, op: CompareOp, bc: Int): Unit = {
        val arg = st.pop()
        val cmpType = tkind match {
          case BytecodeTypeKind.INT => IntType
          case BytecodeTypeKind.CLASS => arg.tpe
          case _ => shouldNotReachHere(tkind)
        }
        val nullValue: Node = cmpType match {
          case IntType => IConst(0)
          case _ => AnyNull(cmpType)
        }
        makeIf(Cmp(cmpType, Condition(op))(arg, nullValue))
      }

      override def binaryIf(tkind: BytecodeTypeKind, op: CompareOp, bc: Int): Unit = {
        val a2 = st.pop()
        val a1 = st.pop()
        val cmpType = tkind match {
          case BytecodeTypeKind.INT => IntType
          case BytecodeTypeKind.CLASS => a1.tpe | a2.tpe
          case _ => shouldNotReachHere(tkind)
        }
        makeIf(Cmp(cmpType, Condition(op))(a1, a2))
      }

      override def tableSwitch(bcDefault: Int, lowMatch: Int, highMatch: Int, bcTargets: Array[Int]): Unit = {
        makeSwitch(st.pop())
      }

      override def lookupSwitch(bcDefault: Int, matches: Array[Int], bcTargets: Array[Int]): Unit = {
        makeSwitch(st.pop())
      }

      def jump(bc: Int): Unit = {
        // do nothing
      }

      def ret(param: Int): Unit = {
        assert(st(param).tpe == ReturnAddressType)
      }

      def jsr(bc: Int): Unit = {
        st push ReturnAddress()
      }

      def doReturn(tkind: BytecodeTypeKind, isLastBytecode: Boolean): Unit = {
        makeReturn( if (tkind.isVoid) Void() else st.pop() )
      }

      def fieldOp(index: Int, akind: FieldAccessKind): Unit = {
        import ConstantPoolAccessResult.*

        val fieldAccess = cp.getField(index, akind)
        fieldAccess.getResult match {
          case OK | DEFERRED =>
            val field = fieldAccess.getObject

            assert(akind.isInstance == !field.isStatic)

            val value = if (akind.isWrite) st.pop() else null
            val obj = if (akind.isInstance) st.pop() else null

            fieldOpImpl(index, cp.getFieldRefClass(index), field, obj, value)

          case ERROR =>
            throwErrorAndHalt(fieldAccess.getError)
        }
      }

      def fieldOpImpl(index: Int, refClass: symlevel.Type, field: Field, obj: Node, value: Node): Unit = {
        val tpe = ValueType.fromSig(field.getType)

        val write = value != null
        val statik = field.isStatic
        val absent = field.getDeclaringClass.isDeferred

        val volat = if (absent) {
          assert(index != DAIGenerator.NO_CP_INDEX)
          false // deferred thunks contain necessary barriers
        } else {
          field.isVolatile
        }

        val finalFieldsRequirePublicationBarrier = !env.enabled(GenerateWriteBarriers) // see JET-12699
        if (write && !statik && field.isFinal && method.isConstructor && (field.getDeclaringClass == method.getDeclaringClass) && finalFieldsRequirePublicationBarrier) {
          needMemBarBeforeReturn = true
        }

        if (!absent) {
          if (!statik) {
            nullCheck(obj)
          } else if (field.getDeclaringClass.hasRunTimeTypeInfo) {
            clinitCheck(field.getDeclaringClass)
            if (env.enabled(ForceAddAggressiveClinitAnalysisAssert) &&
                !write && !method.isClinit &&
                isFieldAnalyzableByClinitAnalysis(field) && isAggressiveClinitAnalysisAllowedFor(field.getDeclaringClass)) {

              AggressiveClinitAnalysisAssert(field)()
            }
          }
        }

        def doFieldOp(): Unit = {

          if (env.enabled(GenerateWriteBarriers) && write && field.getType.isTraceableReference) {
            if (statik) {
              if (currentInlineContext.method.isManaged) {
                WriteBarrier.static(value)
              } else {
                VerificationStaticWriteBarrier(value)
              }
            } else {
              if (currentInlineContext.method.isManaged) {
                WriteBarrier.instance(obj, value)
              } else {
                VerificationInstanceWriteBarrier(obj, value)
              }
            }
          }

          val op = if (absent) {
            tryDeferred(field.getFullName) {
              Deferred.FieldOp(index, field.getType, write, statik)(Deferred.FieldOp.makeArgs(obj, value, write, statik): _*)
            }

          } else {
            (write, statik) match {
              case (false, false) =>
                val g = GetField(field)(obj)
                // String.value field is known to be non-null, state it explicitly.
                // FIXME: use jca for this, but first fix JET-14280
                if (field == Java.Lang.String.value) {
                  NullCheck(trusted = true)(g)
                }
                g

              case (true,  false) => PutField(field)(obj, value)

              case (false, true)  =>
                if (!env.enabled(XGenAsserts) &&
                    field.isSynthetic && field.isFinal && field.getType.jbcKind == BytecodeTypeKind.BOOLEAN && field.getName == "$assertionsDisabled") {
                  // Completely remove Java assertion check.
                  IConst(1)
                } else {
                  ensurePrepared(PreparationRequired.forGetStatic(field))
                  GetStatic(field)
                }

              case (true,  true)  =>
                ensurePrepared(PreparationRequired.forPutStatic(field))
                PutStatic(field)(value)
            }
          }

          if (!write) {
            st push op
          }
        }

        if (write) {
          if (volat) MemBarrier(Set(LOAD_STORE, STORE_STORE))()
          doFieldOp()
          if (volat) MemBarrier(Set(STORE_LOAD, STORE_STORE))()
        } else {
          doFieldOp()
          if (volat) MemBarrier(Set(LOAD_LOAD, LOAD_STORE))()
        }
      }

      def arrayLength(): Unit = {
        val obj = st.pop()
        nullCheck(obj)
        st push jbcArrayLength(obj)
      }

      def jbcArrayLength(obj: Node) = {
        if (rootDeclaringClass.isXScalaType) {
          ScalaArrayLength(obj)
        } else {
