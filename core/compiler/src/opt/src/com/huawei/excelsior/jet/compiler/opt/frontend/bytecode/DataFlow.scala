      def createNew(klass: symlevel.ClassType): New = {
        if (!klass.isAbstractClass && !klass.isInterface) {
          clinitCheck(klass)
          ensurePrepared(PreparationRequired.forType(klass))
          New(SignatureType.fromSymType(klass))()

        } else {
          assert(!klass.isAJManagedType)
          if (klass.isXScalaType) {
            throwErrorAndHalt(RTSProc.JR_ThrowScalaInstantiationError, ImportedIndex(klass))
          } else {
            assert(klass.isJavaReference)
            throwErrorAndHalt(RTSProc.JR_ThrowInstantiationError, ImportedIndex(klass))
          }
        }
      }

