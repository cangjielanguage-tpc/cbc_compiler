      def checkCast(index: Int): Unit = {
        import ConstantPoolAccessResult.*

        val obj = st.pop()

        val typeAccess = cp.getClassType(index)
        typeAccess.getResult match {
          case OK =>
            val targetType = typeAccess.getObject
            if (targetType.isThinClass) {
              assert(targetType.isPolyThinClass)
              ThinCheckCast(targetType)(obj)
            } else {
              // JET-15082 fix: ignore `checkcast` to `ManagedEopType`
              //
              // `ManagedEopType` is fake interface used to represent `ManagedEop` values in compiler.
              // No object implements this interface, therefore, `checkcast` to it will always fail.
              //
              // Moreover, `ManagedEop` may hold an enriched value, but `checkcast` implementation
              // will treat is as plain (see `TypeChecks#lowerInterfaceCast`, `IFaceOps#cast`).
              if (!typeProvider.isManagedEopUnderlyingType(targetType)) {
                if (!rootDeclaringClass.isXScalaType || targetType != typeProvider.getSerializableType) {
                  // scalac inserts such casts (e.g. in scala.collection.SetOps.concat)
                  CheckCast(SignatureType.fromSymType(targetType), trusted = !managedContext)(obj)
                }
              }
            }

          case DEFERRED =>
            tryDeferred(typeAccess.getObject.getName) {
              Deferred.CheckCast(index)(obj)
            }

          case ERROR =>
            throwErrorAndHalt(typeAccess.getError)
        }

        st push obj
      }

