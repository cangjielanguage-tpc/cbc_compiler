      private def arrayOp(put: Boolean, tkind: TKind): Unit = {
        val arrayType = SignatureType.fromSymType(typeProvider.get1DimArrayType(tkind))
        val value   = if (put) st.pop() else null
        val idx     = st.pop()
        val arrObj  = st.pop()

        // Array aggregate optimization is afraid of checks, all of them should be eliminated.
        // NC is optimized by context types, but AIC & ASC are not.

        nullCheck(arrObj)

        val arrLength = jbcArrayLength(arrObj)

        val needIndexCheck = (idx, arrLength) match {
          case (IConst(index), IConst(arrLen)) if (0 <= index) && (index < arrLen) => false
          case _ => true
        }
        if (needIndexCheck) ArrayIndexCheck(arrayType, trusted = noArrayIndexCheck || !managedContext)(arrObj, idx, arrLength)

        val needStoreCheck = put && tkind.isReference && {
          val reallyNeed = (value, arrObj) match {
            case (_: AnyNull, _) => false

            case (cs: ConstString, newArray: AnyNewArray) if !newArray.allocType.isDeferred =>
              // Special handling for string put into new array,
              // general optimization of ArrayStoreCheck is done later.
              val arrType = JavaArrayType(newArray.allocType)
              // TODO: use hierarchy entity and eliminate branching
              if (cs.str.getHost.isXScalaType) {
                !(arrType.arrayElement.asInstanceOf[ReferenceType] >= ReferenceType.xscalaString)
              } else {
                !(arrType.arrayElement.asInstanceOf[ReferenceType] >= ReferenceType.javaLangString)
              }

            case _ => true
          }
          if (!reallyNeed) stats.count(StatsKind.TypeOpt, "arraystorecheck striked out trivial", currentPosition())
          reallyNeed
        }
        if (needStoreCheck) ArrayStoreCheck(arrayType, trusted = noArrayStoreCheck || !managedContext)(arrObj, value)

        if (put) {
          if (env.enabled(GenerateWriteBarriers) && tkind.isReference) {
            if (currentInlineContext.method.isManaged) {
              WriteBarrier.instance(arrObj, value)
            } else {
              VerificationInstanceWriteBarrier(arrObj, value)
            }
          }

          if (!collectArrayAggregate(arrayType, arrObj, idx, value)) {
            ArrayPut(arrayType)(arrObj, idx, value)
          }
        } else {
          st push ArrayGet(arrayType)(arrObj, idx)
        }

      }

      def arrayGet(btkind: BytecodeTypeKind): Unit = { arrayOp(put = false, fromBytecode(btkind)) }

      def arrayPut(btkind: BytecodeTypeKind): Unit = { arrayOp(put = true, fromBytecode(btkind)) }

      private val MAX_JVM_ARITY = 255 // this is mandated by the JVM spec.

      private def createInvokeDynamicOrSigPoly(index: Int, refKind: DAIRefKind, methodType: MethodType, args: Seq[Node]): Deferred = {
        // Runtime code (j.l.i.MethodHandleNatives) defines when appendix argument is null or not null.
        // To simplify this logic we statically assume that all methods have appendix argument
        // except methods with MAX_JVM_ARITY arguments (because they have no place for extra argument).
        // This assumption is verified after resolve of the invoke via assert in RT code.
        val hasAppendix = (methodType.parameterSlotCount + 1) /*appendix*/ <= MAX_JVM_ARITY
        val (newMethodType, newArgs) = if (hasAppendix) {
          (methodType.appendParameterType(SignatureType.javaLangObject), args :+ Null())
        } else (methodType, args)

        Deferred.DynamicOrSigPolyInvoke(index, refKind, newMethodType, hasAppendix)(newArgs: _*)
      }

      def invoke(index: Int, akind: MAK): Unit = {
        import BitFieldExtract.*
        import ConstantPoolAccessResult.*

        val methodTypeErased = MethodType.jbcErased(cp.getRefSignature(index), typeProvider, akind.hasObjectArg)

        var targetArgs = IndexedSeq.fill(methodTypeErased.parameterCount)(st.pop()).reverse

        val dynOrSigPolyInvoke: Option[Node] = akind match {
          case MAK.VIRTUAL | MAK.STATIC if cp.isMethodSignaturePolymorphic(index) =>
            val sigPolyMethodID = cp.getSignaturePolymorphicMethodID(index)
            assert((sigPolyMethodID.isStatic && akind == MAK.STATIC) || akind == MAK.VIRTUAL)

            if (sigPolyMethodID.isMethodHandleInvoker) {
              assert(!sigPolyMethodID.isStatic)
              Some(createInvokeDynamicOrSigPoly(index, DAIRefKind.INVOKE_SIGPOLY, methodTypeErased, targetArgs))
            } else {
              assert(sigPolyMethodID == SigPolyMethodID.INVOKE_BASIC)
              Some(Deferred.SigPolyInvokeBasic(index, methodTypeErased)(targetArgs: _*))
            }
          case MAK.DYNAMIC =>
            LambdaTypeGenerator(_.getLambdaConstructor(rootDeclaringClass, index)) match {
              case None | Some(null) =>
                if (languagePack == LanguagePack.SCALA) {
                  RTSCall(RTSProc.JR_FatalError)(AJString.bstr(s"notImplemented lambda with deferred types: $rootDeclaringClass#$index"))
                  haltBlock(Halt.afterRTSCall(RTSProc.JR_FatalError, s"notImplemented lambda with deferred types: $rootDeclaringClass#$index"))
                  return
                } else {
                  Some(createInvokeDynamicOrSigPoly(index, DAIRefKind.INVOKE_DYNAMIC, methodTypeErased, targetArgs))
                }

              case Some(lambdaConstr) =>
                val newNode = createNew(lambdaConstr.method.getDeclaringClass)
                createInvoke(lambdaConstr, newNode +: targetArgs)
                Some(newNode)
            }
          case _ => None
        }

        if (dynOrSigPolyInvoke.nonEmpty) {
          if (!methodTypeErased.returnType.isZST) {
            st push dynOrSigPolyInvoke.get
          }
          return
        }

        val methodReferenceAccess = cp.getMethodReference(index, akind)

        val result = methodReferenceAccess.getResult match {
          case OK =>
            var targetRef = methodReferenceAccess.getObject
            if (targetRef.methodType.isVarArgs) {
              val VarArgsList(varArgs, varArgTypes) = targetArgs.last
              targetArgs = targetArgs.init ++ varArgs
              targetRef = targetRef.withMethodType(targetRef.methodType.appendVarArgs(varArgTypes)).asInstanceOf[BytecodeMethodReference]
            }

            val target = targetRef.method
            val ajCallKind = target.getAJCallKind

            ajCallKind match {
              case MethodAJCallKind.NORMAL =>
                createInvoke(targetRef, targetArgs)

              case MethodAJCallKind.UNCHECKED_CALL  =>
                createInvoke(target.getUncheckedCallTargetRef, targetArgs)

              case MethodAJCallKind.UNCHECKED_NEW  =>
                assert(managedContext)
                val targetInit = target.getUncheckedNewTargetRef
                val newNode = createNew(targetInit.method.getDeclaringClass)
                createInvoke(targetInit, newNode +: targetArgs)
                newNode

              case MethodAJCallKind.INDIRECT_CALL =>
                createInvoke(targetRef, targetArgs)

              case MethodAJCallKind.CALL_TO_MANAGED =>
                assert(!managedContext)
                createInvoke(targetRef, targetArgs)

              case MethodAJCallKind.THIN_UNCHECKED_CAST => targetArgs match {
                case Seq(thin) =>
                  val targetType = target.getDeclaringClass
                  assert(targetType.isThinClass)
                  ThinCheckCast(targetType, trusted = true)(thin)
                  thin
              }

              case MethodAJCallKind.GET_FLAT_THIN_INTRINSIC => targetArgs match {
                case Seq(struct, offset) =>
                  val targetType = target.getDeclaringClass
                  assert(targetType.isThinClass)
                  if (env.enabled(OptimizeGetFlatThin)) {
                    // These nodes are high-level operations with optimizations and context types. Thus they can be
                    // optimized better than pre-lowered patterns written below. But their optimizations provoke GVN
                    // and code motion to extra execution paths, which decrease interpreter performance by 25%.
                    // TODO: enable in the best future, where BGCM will handle these problems.
                    GetFlatThinCheck(struct, offset)
                    GetFlatThin(targetType)(struct, offset)
                  } else {
                    val addr = Add(struct, Extend(AddrType, AsmType.I32, signExtension = true, offset))
                    val thin = ReinterpretCast(AddrType, ThinType)(addr)
                    ThinCheckCast(targetType, trusted = true)(thin)
                    thin
                  }
              }

              case MethodAJCallKind.INTRINSIC_CALL | MethodAJCallKind.INTRINSIC_WITH_BODY_CALL =>
                target.getAJCallKind match {
                  case MethodAJCallKind.INTRINSIC_CALL =>
                    def fieldOpIntrinsic(obj: Node, value: Node, className: ConstString, fieldName: ConstString): Unit = {
                      val clazz = typeProvider.resolveTypeByName(method.getDeclaringClass, className.stringValue.replace('.', '/'))
                      assert(clazz.isClassOrInterface)
                      assert(!clazz.isThinClass)
                      val field = clazz.findField(fieldName.stringValue)
                      fieldOpImpl(DAIGenerator.NO_CP_INDEX, clazz, field, obj, value)
                    }

                    //to avoid copy&paste we process field access intrinsics here in dataflow
                    target.getIntrinsicType match {
                      case JavaFieldAccess_getBoolean | JavaFieldAccess_getByte | JavaFieldAccess_getChar | JavaFieldAccess_getDouble |
                           JavaFieldAccess_getFloat | JavaFieldAccess_getInt | JavaFieldAccess_getLong | JavaFieldAccess_getObject |
                           JavaFieldAccess_getAJObject | JavaFieldAccess_getShort |
                           AJFieldAccess_getBoolean | AJFieldAccess_getByte | AJFieldAccess_getChar | AJFieldAccess_getDouble |
                           AJFieldAccess_getFloat | AJFieldAccess_getInt | AJFieldAccess_getLong | AJFieldAccess_getObject |
                           AJFieldAccess_getShort => targetArgs match {
                        case Seq(obj, className: ConstString, fieldName: ConstString) =>
                          fieldOpIntrinsic(obj, null, className, fieldName)
                          return // result is already pushed on stack
                      }

                      case JavaFieldAccess_setBoolean | JavaFieldAccess_setByte | JavaFieldAccess_setChar | JavaFieldAccess_setDouble |
                           JavaFieldAccess_setFloat | JavaFieldAccess_setInt | JavaFieldAccess_setLong | JavaFieldAccess_setObject |
                           JavaFieldAccess_setAJObject | JavaFieldAccess_setShort |
                           AJFieldAccess_setBoolean | AJFieldAccess_setByte | AJFieldAccess_setChar | AJFieldAccess_setDouble |
                           AJFieldAccess_setFloat | AJFieldAccess_setInt | AJFieldAccess_setLong | AJFieldAccess_setObject |
                           AJFieldAccess_setShort => targetArgs match {
                        case Seq(obj, value, className: ConstString, fieldName: ConstString) =>
                          fieldOpIntrinsic(obj, value, className, fieldName)
                          return // result is already pushed on stack
                      }

                      case JavaFieldAccess_getLength => targetArgs match {
                        case Seq(obj) =>
                          nullCheck(obj)
                          jbcArrayLength(obj)
                      }

                      case DelayedIntrinsics_getObject => targetArgs match {
                        case Seq(obj, className: ConstString, fieldName: ConstString) =>
                          val cz = typeProvider.findClass(className.stringValue)
                          if (cz == null) {
                            DelayedGet(className.stringValue, fieldName.stringValue, TRefType)(obj)
                          } else {
                            fieldOpIntrinsic(obj, null, className, fieldName)
                            return // result is already pushed on stack
                          }
                      }

                      case DelayedIntrinsics_setObject => targetArgs match {
                        case Seq(obj, value, className: ConstString, fieldName: ConstString) =>
                          val cz = typeProvider.findClass(className.stringValue)
                          if (cz == null) {
                            DelayedPut(className.stringValue, fieldName.stringValue, TRefType)(obj, value)
                          } else {
                            fieldOpIntrinsic(obj, value, className, fieldName)
                            return // result is already pushed on stack
                          }
                      }

                      case DelayedIntrinsics_getInt => targetArgs match {
                        case Seq(obj, className: ConstString, fieldName: ConstString) =>
                          val cz = typeProvider.findClass(className.stringValue)
                          if (cz == null) {
                            DelayedGet(className.stringValue, fieldName.stringValue, IntType)(obj)
                          } else {
                            fieldOpIntrinsic(obj, null, className, fieldName)
                            return // result is already pushed on stack
                          }
                      }

                      case DelayedIntrinsics_setInt => targetArgs match {
                        case Seq(obj, value, className: ConstString, fieldName: ConstString) =>
                          val cz = typeProvider.findClass(className.stringValue)
                          if (cz == null) {
                            DelayedPut(className.stringValue, fieldName.stringValue, IntType)(obj, value)
                          } else {
                            fieldOpIntrinsic(obj, value, className, fieldName)
                            return // result is already pushed on stack
                          }
                      }

                      case DelayedIntrinsics_getLong => targetArgs match {
                        case Seq(obj, className: ConstString, fieldName: ConstString) =>
                          val cz = typeProvider.findClass(className.stringValue)
                          if (cz == null) {
                            DelayedGet(className.stringValue, fieldName.stringValue, LongType)(obj)
                          } else {
                            fieldOpIntrinsic(obj, null, className, fieldName)
                            return // result is already pushed on stack
                          }
                      }

                      case DelayedIntrinsics_setLong => targetArgs match {
                        case Seq(obj, value, className: ConstString, fieldName: ConstString) =>
                          val cz = typeProvider.findClass(className.stringValue)
                          if (cz == null) {
                            DelayedPut(className.stringValue, fieldName.stringValue, LongType)(obj, value)
                          } else {
                            fieldOpIntrinsic(obj, value, className, fieldName)
                            return // result is already pushed on stack
                          }
                      }

                      case _ => loadIntrinsic(target, target.getIntrinsicType, method, targetArgs)
                    }

                  case MethodAJCallKind.INTRINSIC_WITH_BODY_CALL =>
                    Option(target.getIntrinsicWithBodyType)
                      .flatMap(itype => loadIntrinsicWithBody(target, itype, method, targetArgs))
                      .getOrElse(createInvoke(targetRef, targetArgs))

                  case x => shouldNotReachHere(x)
                }
            }

          case DEFERRED =>
            val methodRef = methodReferenceAccess.getObject
            tryDeferred(s"${methodRef.refClass.getName}.${methodRef.methodName}") {
              Deferred.UnresolvedInvoke(index, methodRef)(targetArgs: _*)
            }

          case ERROR =>
            throwErrorAndHalt(methodReferenceAccess.getError)
        }

        if (!methodTypeErased.returnType.isZST) {
          st push result
        }
      }

      private def createInvoke(targetRef: MethodReference, targetArgs: Seq[Node]) = {
        val target = targetRef.method
        val refClass = targetRef.refClass

        def receiver = { assert(targetRef.hasReceiverParameter); targetArgs(targetRef.getReceiverArgIndex)}

        if (!target.isStatic) {
          // De facto, Unsafe instance is always non-null. Also note that all its methods are static-like.
          val trustedUnsafeCall =
            !env.enabled(NoAggressiveUnsafeNullCheckElimination) &&
              rootDeclaringClass.isOptimizedAggressively &&
              target.getDeclaringClass.isSunMiscUnsafe
          nullCheck(receiver, forceTrusted = trustedUnsafeCall)
          if (trustedUnsafeCall) {
            stats.count(StatsKind.UnsafeOpt, "remove nullcheck", currentPosition())
          }
        }

        if (target.isThinConstructor) {
          assert(target.isStatic)
          nullCheck(targetArgs.head)
        }

        ensurePrepared(PreparationRequired.forInvoke(targetRef))
        val invoke = if (target.isAJDelayedIntrinsic) {
          val hasZSTRetByVal = target.getMethodType.hasRetByValParameter && target.getReturnType.isZST
          val adjustedArgs = Option.when(hasZSTRetByVal)(Void()).toSeq ++ targetArgs
          val n = DelayedMethodAddr(target.getAJDelayedIntrinsicClassName, target.getAJDelayedIntrinsicName)()
          Call(targetRef.withMethodType(targetRef.realMethodType))(n +: adjustedArgs*)

        } else if (target.isIndirectCall) {
          assert(targetRef.accessKind == MethodReferenceAccessKind.STATIC)
          assert(targetRef.methodType.parameterCount == targetRef.realMethodType.parameterCount + 1)
          Call(targetRef.withMethodType(targetRef.realMethodType))(targetArgs*)

        } else if (targetRef.isInterfCall) {
          if (target.getDeclaringClass.isXScalaAnyRef || target.getDeclaringClass.isJavaLangObject) {
            // Do early deinterfization of such cases for O1 (to avoid special handling of such calls in lowering)
            val deinterfRef = targetRef.withRefClassAndAccessKind(CompiledType(target.getDeclaringClass), MethodReferenceAccessKind.VIRTUAL)
            Invoke(deinterfRef)(targetArgs*)

          } else {
            val ciao = WeakCast(refClass)(receiver, WeakCast.NoCheck())
            InvokeInterface(targetRef, ciao)(targetArgs*)
          }

        } else {
          val devirtRef = if (target.isAJInlineForced && targetRef.accessKind == MethodReferenceAccessKind.VIRTUAL) {
            // Do early devirtualization of such cases to not waste time later
            // (and in case regular devirtualization is disabled).
            assert(target.isFinal || refClass.isFinal || refClass.isUltraThinClass)
            targetRef.withAccessKind(MethodReferenceAccessKind.SPECIAL)
          } else {
            targetRef
          }
          Invoke(devirtRef)(targetArgs*)
        }

        invoke match {
          case AnyDirectCall(t) if t.isAjNoReturn || locallyAnalyzeMethod(t).exists(_.isNoReturn) =>
            if (t.isAjNoReturn) {
              stats.count(NoReturn, s"call of method ${t.getName} marked as 'NoReturn' because it marked as 'AjNoReturn'")
            } else {
              stats.count(NoReturn, s"call of method ${t.getName} analyzed as 'NoReturn'")
            }
            haltBlock(Halt.explained("call marked as 'NoReturn'"))
          case _ => invoke
        }
      }

