#!/usr/bin/env python3
"""Compile SDK CHIR inputs independently and inventory temporary compiler stubs.

Source SDK envsetup.sh before running. This is a compilation audit, not a test
suite; it does not execute the generated bytecode. Requires AuditCHIRStubs and
RejectCHIRStubs options in the selected compiler jar.
"""

import argparse
import hashlib
import json
import shlex
import subprocess
import time
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sdk", type=Path, required=True)
    parser.add_argument("--jar", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--filter", default="")
    parser.add_argument("--strict", action="store_true")
    parser.add_argument("--timeout", type=int, default=300)
    args = parser.parse_args()
    args.sdk = args.sdk.resolve()
    args.jar = args.jar.resolve()
    args.output = args.output.resolve()
    args.output.mkdir(parents=True, exist_ok=True)
    inputs = sorted(p for folder in ("std-packages", "stdx-packages")
                    for p in (args.sdk / "tools/lib" / folder).glob("*.chir"))
    inputs = [p for p in inputs if args.filter in p.name]
    manifest = {"jar": str(args.jar),
                "jar_sha256": hashlib.sha256(args.jar.read_bytes()).hexdigest(),
                "strict": args.strict,
                "inputs": [{"path": str(p), "bytes": p.stat().st_size,
                            "sha256": hashlib.sha256(p.read_bytes()).hexdigest()}
                           for p in inputs]}
    manifest_path = args.output / "manifest.json"
    if manifest_path.exists():
        previous = json.loads(manifest_path.read_text())
        previous.pop("combined", None)
        if previous != manifest:
            parser.error("output directory belongs to a different compiler/input manifest")
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    jobs = [(p.stem, [p]) for p in inputs]
    results = []
    for name, files in jobs:
        directory = args.output / name
        directory.mkdir(exist_ok=True)
        result_path = directory / "result.json"
        if result_path.exists():
            results.append(json.loads(result_path.read_text()))
            continue
        command = ["java", "-Xmx3g", "-jar", str(args.jar),
                   "+GenCbcStdLib", "+IgnoreSourceFileNameForCbc", "+AuditCHIRStubs",
                   f"-cangjiehome={args.sdk}", f"-outputname={directory / name}",
                   "-foreignlibs=cangjie-runtime"]
        if args.strict:
            command.append("+RejectCHIRStubs")
        command.extend(map(str, files))
        (directory / "command.txt").write_text(shlex.join(command) + "\n")
        start = time.monotonic()
        with (directory / "build.log").open("w") as log:
            try:
                status = subprocess.run(command, cwd=directory, stdout=log,
                                        stderr=subprocess.STDOUT, timeout=args.timeout).returncode
            except subprocess.TimeoutExpired:
                status = "timeout"
        methods, intrinsics, stubs = {}, [], []
        for line in (directory / "build.log").read_text(errors="replace").splitlines():
            if line.startswith("CBC-CHIR-AUDIT\t"):
                _, kind, method, source_name, source_file, chir = line.split("\t", 5)
                record = {"method": method, "source_name": source_name,
                          "source_file": source_file, "chir": chir}
                methods[method] = record
                if kind.startswith("intrinsic:"):
                    intrinsics.append(dict(record, intrinsic=kind.split(":", 1)[1]))
            elif line.startswith("CBC-STUBBED-METHOD: "):
                stubs.append({"method": line.split(": ", 1)[1], "stack": []})
            elif line.startswith("CBC-STUBBED-REASON: ") and stubs:
                stubs[-1]["reason"] = line.split(": ", 1)[1]
            elif line.startswith("CBC-STUBBED-AT: ") and stubs:
                stubs[-1]["stack"].append(line.split(": ", 1)[1])
        for stub in stubs:
            stub.update(methods.get(stub["method"], {}))
        cbc = directory / (name + ".cbc")
        result = {"package": name, "inputs": list(map(str, files)), "exit": status,
                  "seconds": round(time.monotonic() - start, 2),
                  "cbc_bytes": cbc.stat().st_size if cbc.exists() else 0,
                  "parsed_methods": len(methods), "stubs": stubs,
                  "intrinsic_stubs": intrinsics}
        result_path.write_text(json.dumps(result, indent=2) + "\n")
        results.append(result)
        print(f"{name}: exit={status}, methods={len(methods)}, "
              f"fallbacks={len(stubs)}, intrinsic_stubs={len(intrinsics)}, "
              f"{result['seconds']}s", flush=True)
    (args.output / "results.json").write_text(json.dumps(results, indent=2) + "\n")


if __name__ == "__main__":
    main()
